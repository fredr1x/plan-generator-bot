    @Inject
    Messenger bot;

    /** /instruction: the list of sections. */
    void show(long chat) {
        bot.send(chat, LIST, listButtons());
    }

    void onCallback(long chat, long msgId, String cbId, String[] p) {
        bot.answer(cbId, null);
        int n = Integer.parseInt(p[1]);
        if (n <= 0 || n > SECTIONS.size()) {
            bot.edit(chat, msgId, LIST, listButtons());
            return;
        }
        List<InlineButton> nav = new ArrayList<>();
        nav.add(btn("← Список", "ins:0"));
        if (n < SECTIONS.size()) nav.add(btn("Дальше →", "ins:" + (n + 1)));
        bot.edit(chat, msgId, SECTIONS.get(n - 1).text(), Kb.rows().add(nav).build());
    }

    private static dev.ydt.plangen.telegram.Dto.InlineKeyboard listButtons() {
        Kb.Rows rows = Kb.rows();
        for (int i = 0; i < SECTIONS.size(); i++) {
            rows.add(btn(SECTIONS.get(i).button(), "ins:" + (i + 1)));
        }
        return rows.build();
    }

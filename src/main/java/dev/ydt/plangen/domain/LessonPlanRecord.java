package dev.ydt.plangen.domain;

import io.quarkus.hibernate.orm.panache.PanacheEntityBase;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.Instant;
import java.time.LocalDate;
import java.util.List;

@Entity
@Table(name = "lesson_plans")
public class LessonPlanRecord extends PanacheEntityBase {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    public Long id;

    @Column(name = "teacher_id")
    public long teacherId;

    @Column(name = "plan_date")
    public LocalDate planDate;

    public String classes;

    public int students;

    public String section;

    public String topic;

    public String objectives;

    @Column(name = "content_json")
    public String contentJson;

    public String model;

    @Column(name = "created_at")
    public Instant createdAt = Instant.now();

    public static List<LessonPlanRecord> latest(long teacherId, int limit) {
        return find("teacherId = ?1 order by createdAt desc", teacherId).page(0, limit).list();
    }

    /** Plans generated by the model since the given moment (copies of existing plans do not count). */
    public static long countSince(long teacherId, Instant since) {
        return count("teacherId = ?1 and createdAt >= ?2 and model <> 'copy'", teacherId, since);
    }
}
